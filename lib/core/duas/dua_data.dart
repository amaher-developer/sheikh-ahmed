/// أدعية مأثورة — supplications, kept apart from the azkar on purpose.
///
/// An azkar list is bound to an occasion: morning, evening, sleeping, after
/// prayer, on waking, at a meal, at the adhan. Every one of them answers
/// "when X happens, say this", and finishing one is a thing you do each day —
/// which is why that screen counts a daily progress.
///
/// A du'a answers nothing of the kind. It is asked when it is needed, not on
/// a schedule, and there is no sense in which you complete them for the day.
/// Under the azkar the app would have kept reporting "3 of 18 today" over a
/// list nobody is meant to finish.
///
/// Grouped by what is being asked for, because that is the only question
/// anyone arrives with. A reader in debt wants الرزق; a reader who has just
/// done something wants الاستغفار. Seventy in one flat list answers neither.
///
/// Every text here is either Quran or from the standard hadith collections —
/// Bukhari, Muslim, Abu Dawud, at-Tirmidhi, an-Nasa'i, Ibn Majah — as
/// gathered in حصن المسلم. Nothing composed.
library;

/// One supplication.
class Dua {
  final String id;

  /// The du'a itself, in Arabic. Not a translation key: this is what the
  /// user says, and it does not change with the interface language.
  final String textAr;

  /// How many times it is traditionally repeated. 1 for almost all of them —
  /// a du'a is asked and meant, not counted off.
  final int count;

  const Dua({required this.id, required this.textAr, this.count = 1});
}

/// A themed set of supplications.
class DuaGroup {
  final String id;
  final String titleKey;
  final List<Dua> duas;

  const DuaGroup({
    required this.id,
    required this.titleKey,
    required this.duas,
  });
}

