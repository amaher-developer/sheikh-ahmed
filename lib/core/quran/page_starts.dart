/// The page a verse falls on, or null if it is outside the Mus'haf.
///
/// The last page starting at or before the verse — the same scan
/// [hizbQuarterFor] uses, and correct for the same reason: the table is
/// already in recitation order.
int? pageForAyah(int surahNumber, int ayahNumber) {
  int? found;
  for (final p in kPageStarts) {
    final beforeOrAt = p.surahNumber < surahNumber ||
        (p.surahNumber == surahNumber && p.ayahNumber <= ayahNumber);
    if (!beforeOrAt) break;
    found = p.page;
  }
  return found;
}

/// The verse [page] opens on, or null for a page outside 1..604.
PageStart? pageStartFor(int page) =>
    page < 1 || page > kPageStarts.length ? null : kPageStarts[page - 1];
